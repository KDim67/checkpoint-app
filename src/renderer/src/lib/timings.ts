/**
 * Durations the UI waits before undoing something it showed.
 *
 * Named because the copy tick was written eleven times at three different
 * lengths, so the same gesture confirmed itself at a different speed depending
 * on which button you pressed.
 */

/** How long a button says "copied" before it goes back to saying what it does. */
export const COPIED_FEEDBACK_MS = 2000

/** How long a toast stays up. */
export const TOAST_DISMISS_MS = 2000

/** How long a settings row says it saved. */
export const SAVED_FEEDBACK_MS = 2000
